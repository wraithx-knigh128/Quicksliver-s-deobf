"""Pack the generated audio into four upload-friendly "atlas" files.

Roblox limits how many audio assets an account may upload each month, so instead of
80 separate uploads the game plays regions of four larger files using
Sound.PlaybackRegion / Sound.LoopRegion:

    audio/atlas/veil_sfx.ogg       every SFX + voice grunt
    audio/atlas/veil_ambience.ogg  the four looping ambience beds
    audio/atlas/veil_music_a.ogg   menu, select, story, victory themes
    audio/atlas/veil_music_b.ogg   the three battle themes
    audio/atlas/veil_announcer.ogg the imported announcer lines (optional upload)

It also writes src/shared/AudioAtlas.luau with the region table.

    python3 tools/build_atlas.py
"""
import glob
import os
import subprocess
import numpy as np

SR = 44100
HERE = os.path.dirname(os.path.abspath(__file__))
AUDIO = os.path.normpath(os.path.join(HERE, "..", "audio"))
OUT = os.path.join(AUDIO, "atlas")
LUAU = os.path.normpath(os.path.join(HERE, "..", "src", "shared", "AudioAtlas.luau"))
GAP = 0.35

GROUPS = {
    "sfx": lambda n: not n.startswith(("music_", "amb_", "ann_")),
    "ambience": lambda n: n.startswith("amb_"),
    "music_a": lambda n: n in ("music_menu", "music_select", "music_story", "music_victory"),
    "music_b": lambda n: n in ("music_battle_a", "music_battle_b", "music_boss"),
    # user-supplied announcer pack (tools/import_user_sounds.py): its own upload
    "announcer": lambda n: n.startswith("ann_"),
}


def decode(path):
    raw = subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-i", path, "-f", "f32le", "-ac", "2", "-ar", str(SR), "-"],
        capture_output=True,
        check=True,
    ).stdout
    return np.frombuffer(raw, dtype="<f4").reshape(-1, 2)


def encode(path, data):
    pcm = (np.clip(data, -1, 1) * 32767).astype("<i2").tobytes()
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "s16le", "-ar", str(SR), "-ac", "2", "-i", "-", "-c:a", "libvorbis", "-q:a", "6", path],
        input=pcm,
        check=True,
    )


def main():
    os.makedirs(OUT, exist_ok=True)
    files = sorted(glob.glob(os.path.join(AUDIO, "*.ogg")))
    regions = {}
    for group, pred in GROUPS.items():
        chunks = []
        cursor = 0.0
        for f in files:
            name = os.path.splitext(os.path.basename(f))[0]
            if not pred(name):
                continue
            data = decode(f)
            dur = len(data) / SR
            regions[name] = (group, round(cursor, 4), round(dur, 4))
            chunks.append(data)
            gap = np.zeros((int(GAP * SR), 2), dtype=np.float32)
            chunks.append(gap)
            cursor += dur + GAP
        if not chunks:
            continue
        atlas = np.concatenate(chunks)
        encode(os.path.join(OUT, f"veil_{group}.ogg"), atlas)
        print(f"{group}: {len(atlas) / SR:.1f}s")
    lines = [
        "--!nonstrict",
        "-- AUTO-GENERATED by tools/build_atlas.py. Do not edit by hand.",
        "-- Regions (seconds) of each sound inside the four uploaded audio atlases.",
        "",
        "return {",
    ]
    for name in sorted(regions):
        g, start, dur = regions[name]
        lines.append(f'\t{name} = {{ atlas = "{g}", start = {start}, length = {dur} }},')
    lines.append("}")
    with open(LUAU, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {len(regions)} regions to {LUAU}")


if __name__ == "__main__":
    main()
