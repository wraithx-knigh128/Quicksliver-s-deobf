// The Origin tab: two readings (AI-written, copied) with the evidence behind each. Every number on this page comes from a
// signal listed on it. Anything that came from the script or from a search result is inserted as text.

import { h, pct } from './dom.js';

const section = (title, body, aside) => h('section.section', h('h3', h('span', title), aside || null), h('div.body', body));

function gauge(title, value, label, sub, kind) {
  const bar = h('div.meter.tall' + (kind ? '.' + kind : ''), h('i', { style: { width: `${Math.round((value || 0) * 100)}%` } }));
  return h('div.verdict', h('h3', title), h('div.pct', value == null ? '—' : pct(value)), h('div.vlabel', label), bar, h('div.vsub', sub));
}

const strengthBar = (s) => {
  const i = h('i', { style: { width: `${Math.round(Math.abs(s) * 50)}%`, [s >= 0 ? 'left' : 'right']: '50%' } });
  i.className = s >= 0 ? 'ai' : 'human';
  return h('span.strength', { title: s >= 0 ? 'points towards AI-written' : 'points towards hand-written' }, i);
};

function signalTable(signals) {
  if (!signals.length) return h('p.dim', 'Nothing measurable in this text.');
  return h('table.signals', [
    h('thead', h('tr', [h('th', 'Signal'), h('th', 'What was measured'), h('th', { title: 'Left of the middle: reads hand-written. Right: reads AI-written.' }, 'Points to')])),
    h('tbody', signals.map((s) => h('tr', [
      h('td', [h('b', s.label), h('div.faint', s.why)]),
      h('td.mono', s.value),
      h('td', strengthBar(s.strength)),
    ]))),
  ]);
}

/**
 * @param {{subject: string, analysis: object, online: object|null, busy: boolean}} state
 * @param {{search(): void, deobfuscate(): void, useInput(): void}} act
 */
export function originView(state, act) {
  const wrap = h('div.origin');
  const a = state.analysis;
  if (!a) {
    wrap.append(h('div.empty', h('b', 'Origin check'), h('span', 'Does this code read like it was written by an AI assistant, and does it look copied from somewhere? Put a script in and press Origin check.')));
    return wrap;
  }
  wrap.append(h('p.dim', { style: { margin: 0 } }, [`Looking at: ${state.subject}. `, `${a.codeLines.toLocaleString()} code lines. `, h('b', 'This is an estimate, not proof: '), 'style is a weak clue, and a match online does not say who wrote the code first.']));
  if (!a.assessable) {
    wrap.append(h('p.note.warn', a.reason + ' Style cannot be read from text like this.'));
    wrap.append(h('div', h('button.btn', { type: 'button', onclick: act.deobfuscate }, 'Deobfuscate first, then check')));
    return wrap;
  }
  const online = state.online;
  const skid = online && online.searched && online.share !== null ? online.share : null;
  const hints = a.skid.signals.length;
  const aiGauge = state.derived
    ? gauge('Written by AI (vibe-coded)', null, 'Cannot be read from rebuilt code', 'names, comments and layout were generated by QuickSilver', 'ai')
    : gauge('Written by AI (vibe-coded)', a.ai.score, a.ai.label, `${a.ai.measured} signal${a.ai.measured === 1 ? '' : 's'} measured · confidence ${a.confidence}`, 'ai');
  const copyGauge = skid !== null
    ? gauge('Copied from elsewhere', skid, online.label, `${online.matches[0].repo} / ${online.matches[0].path}`, 'skid')
    : online && online.searched
      ? gauge('Copied from elsewhere', 0, online.label, 'no public file matched the lines that were searched', 'skid')
      : gauge('Copied from elsewhere', hints ? a.skid.hint : null, 'Not searched yet', hints ? `${hints} hint${hints === 1 ? '' : 's'} in the text (these are clues, not a measurement); search GitHub to check` : 'search GitHub to check', 'skid');
  wrap.append(h('div.verdicts', [aiGauge, copyGauge]));
  if (state.derived) wrap.append(h('p.note.warn', `QuickSilver rebuilt this code from ${state.derivedFrom || 'an obfuscator'}, so its variable names, comments and layout are not the author's. The style reading is not meaningful; the search below still works, on the strings and constants that survived.`));
  if (a.confidence === 'low') wrap.append(h('p.note.info', 'The script is short. With so little text a style reading is close to a coin toss.'));

  if (!state.derived) wrap.append(section('Why it reads this way (AI-written)', signalTable(a.ai.signals)));

  const skidBody = [];
  if (a.skid.signals.length) {
    skidBody.push(h('ul.list', a.skid.signals.map((s) => h('li', [
      h('b', s.label), h('span.mono', { style: { marginLeft: '8px' } }, s.value),
      h('div.faint', s.why),
      s.items ? h('ul', { style: { margin: '4px 0 0', paddingLeft: '16px' } }, s.items.map((it) => h('li.mono', { style: { border: 0, padding: '1px 0' } }, `line ${it.line}: ${it.text}`))) : null,
    ]))));
  } else skidBody.push(h('p.dim', 'No credit lines, invites, links, public libraries or style changes were found in the text.'));
  wrap.append(section('Signs that other people are involved', skidBody));

  // online search
  const body = [];
  if (!online) {
    body.push(h('p', `QuickSilver can look for ${a.fingerprints.length} distinctive lines of this script in GitHub's public code. Only those lines are sent (to this site's server, which asks GitHub); the rest of the script never leaves your browser.`));
    body.push(h('div', h('button.btn.primary', { type: 'button', disabled: state.busy || !a.fingerprints.length, onclick: act.search }, state.busy ? 'Searching…' : 'Search GitHub for these lines')));
    if (!a.fingerprints.length) body.push(h('p.note.info', 'There are no distinctive lines to search for.'));
  } else if (!online.searched) {
    body.push(h('p.note.warn', online.note || 'The search could not be done.'));
    body.push(h('div', h('button.btn', { type: 'button', onclick: act.search }, 'Try again')));
  } else {
    body.push(h('p', `${online.fingerprintsFound} of ${online.fingerprintsSearched} lines were found in public files. ${online.label}.`));
    if (online.note) body.push(h('p.note.warn', online.note));
    if (online.matches.length) {
      body.push(h('table.signals', [
        h('thead', h('tr', [h('th', 'File'), h('th', 'Lines found'), h('th', 'Share of your script in it')])),
        h('tbody', online.matches.map((m) => h('tr', [
          h('td', [h('a', { href: m.url, target: '_blank', rel: 'noopener noreferrer' }, `${m.repo}/${m.path}`)]),
          h('td.mono', String(m.fingerprintHits)),
          h('td.mono', m.coverage ? `${pct(m.coverage.share)} (${m.coverage.matched} of ${m.coverage.total} lines)` : 'not measured'),
        ]))),
      ]));
    }
    body.push(h('p.note', 'A public copy only shows that the same text exists elsewhere. It cannot show who wrote it first, and it may be the original author’s own page.'));
  }
  wrap.append(section('Does the same code exist online?', body, h('span.badge', online && online.searched ? online.provider || 'searched' : 'not searched')));

  wrap.append(h('p.faint', { style: { fontSize: '12px' } }, 'How the AI reading works: each signal above is measured on the text and weighed with a fixed weight; the weights were set by hand and checked on a handful of files. They have not been tested on a large labelled collection, so treat the percentage as a hint.'));
  return wrap;
}
