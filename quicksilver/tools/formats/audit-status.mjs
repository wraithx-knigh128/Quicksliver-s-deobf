// The status of every format this project has worked on, derived from the measured data and the code, not typed in.
//
//   node tools/formats/audit-status.mjs [--write]      (writes docs/AUDIT.md; without --write it prints)
//
// Inputs: data/research/format-db.json (the six measured categories per configuration), data/research/format-records.json (closed tools, public samples read as text),
// data/research/corpus-eval.json (the public collection, by folder), the source tree (does the module a capability needs exist?) and docs/KNOWN-ISSUES.md (which numbered issue
// names the target). Nothing here is a claim: a target with no measurement says so.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { METHODS } from '../../src/core/metrics.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const rd = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const db = rd('data/research/format-db.json');
const records = rd('data/research/format-records.json').records;
const issues = fs.readFileSync(path.join(root, 'docs/KNOWN-ISSUES.md'), 'utf8');
const exists = (p) => fs.existsSync(path.join(root, p));
const pct = (x) => (x == null ? 'n/a' : `${Math.round(x * 100)}%`);
const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null);

// target -> the project in the database, a filter on configs, the modules a recovery of it needs, and the KNOWN-ISSUES rows that name it
const TARGETS = [
  { label: 'Obscura, plain VM (vm) \u2014 lifted since Prompt XI', project: 'obscura', config: /^vm$/, code: ['src/recover/obscura-vm.js', 'src/recover/vmprofile.js'], rows: [37, 43, 44] },
  { label: 'Obscura, hardened VM (vm-max, vm-cached)', project: 'obscura', config: /^vm-/, code: ['src/recover/vmprofile.js'], rows: [37, 43] },
  { label: 'Obscura, other modes (lightweight, level-1..3)', project: 'obscura', config: /^(?!vm)/, code: ['src/recover/obscura.js', 'src/adaptive/strategies/dispatch.js'], rows: [27, 33] },
  { label: 'RealObfuscator (lightweight, native, vm)', project: 'realobfuscator', code: ['src/detect/families.js'], rows: [24, 31] },
  { label: 'XFuscator (character / constant recovery)', project: 'xfuscator', code: ['src/recover/xfuscator.js'], rows: [29, 33] },
  { label: 'LuaXen, AST stage', project: 'luaxen', config: /ast/, code: ['src/adaptive/strategies/dispatch.js'], rows: [27, 28] },
  { label: 'LuaXen, IronBrikked VM stage', project: 'luaxen', config: /ironbrikked|both/, code: ['src/recover/ironbrew.js'], rows: [28] },
  { label: 'Zartha \u2014 lifted since Prompt XII', project: 'zartha', code: ['src/recover/zartha-vm.js'], rows: [36, 51, 52] },
  { label: 'FusGato', project: 'fusgato', code: [], rows: [28, 55] },
  { label: 'zynaa / LuaObfuscator', project: 'zynaa', code: ['src/passes/evaluate.js', 'src/passes/strtable.js'], rows: [30, 32] },
  { label: 'IronBrew 2', project: 'ironbrew2', code: ['src/recover/ironbrew.js', 'src/recover/ib2-templates.js'], rows: [] },
  { label: 'Hercules (1.5 .. 2.0.0)', project: 'hercules', code: ['src/recover/hercules.js', 'src/recover/hercules-vm.js'], rows: [15, 16, 17] },
  { label: 'Prometheus', project: 'prometheus', code: ['src/recover/prometheus.js', 'src/recover/vmify.js'], rows: [] },
  { label: 'Layered / mixed chains', project: 'mixed', code: ['src/adaptive/strategies/dispatch.js'], rows: [22] },
];

const lines = [];
const out = (s = '') => lines.push(s);
out('# Audit: what is implemented, measured, and not');
out();
out('_Generated by `node tools/formats/audit-status.mjs --write` from `data/research/format-db.json`, `data/research/format-records.json`, `data/research/corpus-eval.json`, the source tree and `docs/KNOWN-ISSUES.md`. Do not edit by hand: change the data or the code and run it again._');
out();
out(`Database \`${db.schema}\` measured on the scorecard of ${db.inputs.scorecard}: ${db.inputs.scorecardFixtures} fixtures. Engine: ${db.engine}.`);
out();
out('## How to read the numbers');
out();
out('A result is described by separate categories that are never averaged into one. Each has one definition (`src/core/metrics.js`):');
out();
for (const [k, v] of Object.entries(METHODS)) out(`* **${k}**: ${v}`);
out();
out('Status words: **verified** (every judged fixture of the configuration passes the gates), **partial** (some do), **experimental** (identified and measured, below the gates), **unsupported** (identified or detected, not recovered), **identification-only** (no fixtures, only a rule).');
out();

out('## Tools with fixtures (generated by the tool, run in isolation)');
out();
out('| Target | Fixtures | Identified | Structure before→after | Semantic before→after | Runtime same/judged (not judged) | Complete | VM strings recovered | ms mean | Status |');
out('|---|---|---|---|---|---|---|---|---|---|');
for (const t of TARGETS) {
  const p = db.projects.find((x) => x.id === t.project);
  if (!p) { out(`| ${t.label} | no fixtures | | | | | | | | none |`); continue; }
  const cfgs = p.versions.flatMap((v) => v.configs.map((c) => ({ ...c, version: v.version }))).filter((c) => !t.config || t.config.test(c.config));
  if (!cfgs.length) { out(`| ${t.label} | no fixtures | | | | | | | | none |`); continue; }
  const sum = (f) => cfgs.reduce((a, c) => a + (f(c) || 0), 0);
  const cats = cfgs.map((c) => c.categories).filter(Boolean);
  const w = (get) => { const xs = cfgs.flatMap((c) => { const v = get(c.categories); return v == null ? [] : Array(c.samples).fill(v); }); return mean(xs); };
  const sb = w((c) => c.structure && c.structure.before); const sa = w((c) => c.structure && c.structure.after);
  const fb = w((c) => c.semantic && c.semantic.before); const fa = w((c) => c.semantic && c.semantic.after);
  const same = cats.reduce((a, c) => a + (c.runtime ? c.runtime.same : 0), 0); const judged = cats.reduce((a, c) => a + (c.runtime ? c.runtime.judged : 0), 0); const notJ = cats.reduce((a, c) => a + (c.runtime ? c.runtime.notJudged : 0), 0);
  const complete = cats.reduce((a, c) => a + (c.completeness ? c.completeness.complete : 0), 0); const of = cats.reduce((a, c) => a + (c.completeness ? c.completeness.of : 0), 0);
  const vm = cfgs.filter((c) => c.categories && c.categories.vmConstants); const vmr = vm.length ? mean(vm.flatMap((c) => Array(c.categories.vmConstants.fixtures).fill(c.categories.vmConstants.recall))) : null;
  const ms = mean(cats.map((c) => c.stability && c.stability.msMean).filter((x) => x != null));
  const statuses = [...new Set(cfgs.map((c) => c.status))];
  const rank = ['verified', 'partial', 'experimental', 'unsupported'];
  const status = statuses.length === 1 ? statuses[0] : `mixed (${rank.filter((s) => statuses.includes(s)).join(', ')})`;
  out(`| ${t.label} | ${sum((c) => c.samples)} | ${t.project === 'mixed' ? 'n/a (layered)' : `${sum((c) => c.detected)}/${sum((c) => c.samples)}`} | ${sb == null ? 'n/a' : `${pct(sb)}→${pct(sa)}`} | ${pct(fb)}→${pct(fa)} | ${same}/${judged} (${notJ}) | ${of ? `${complete}/${of}` : 'n/a'} | ${vmr == null ? 'n/a' : pct(vmr)} | ${ms == null ? 'n/a' : Math.round(ms)} | ${status} |`);
}
out();
out('Runtime equivalence is necessary, not sufficient: a build whose virtual machine is left in the output still runs like the original, so it can be runtime-equivalent and, at the same time, **not complete** (the completeness column, and `unsupported` in the status). A "mixed" chain has no single tool to identify, so its identification column is 0 by construction.');
out();
out('Where "Runtime … (not judged)" is non-zero, the number in brackets counts fixtures the **tool’s own output** did not run like the original on any reference runtime; they are not charged to the engine (and not credited to it either).');
out();

out('## Version-by-version matrix (every measured configuration)');
out();
out('One row per version and configuration, in the six categories of `src/core/metrics.js`. Fixture counts are small per row (one per sample program, 4 to 8): a row says how the engine did on those fixtures, not how it would do on every script the tool can write.');
out();
for (const p of db.projects.filter((x) => x.versions.some((v) => v.configs.length))) {
  out(`### ${p.name}${p.id === 'mixed' ? '' : ` (${p.support})`}`);
  out();
  out('| Version | Configuration | n | Identified | Structure | Semantic | Runtime same/judged (not judged) | Complete | VM strings | ms (failures) | Status |');
  out('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const v of p.versions) for (const c of v.configs) {
    const k = c.categories; if (!k) continue;
    out(`| ${v.version} | ${c.config} | ${c.samples} | ${p.id === 'mixed' ? 'n/a' : `${k.identification.detected}/${k.identification.of}`} | ${k.structure ? `${pct(k.structure.before)}→${pct(k.structure.after)}` : 'n/a'} | ${pct(k.semantic.before)}→${pct(k.semantic.after)} | ${k.runtime.same}/${k.runtime.judged}${k.runtime.notJudged ? ` (${k.runtime.notJudged})` : ''} | ${k.completeness ? `${k.completeness.complete}/${k.completeness.of}` : 'n/a'} | ${k.vmConstants ? pct(k.vmConstants.recall) : '-'} | ${k.stability.msMean ?? 'n/a'}${k.stability.failures ? ` (${k.stability.failures})` : ''} | ${c.status} |`);
  }
  out();
}

out('## Code behind each target (does the module exist?)');
out();
for (const t of TARGETS) {
  const present = t.code.map((c) => `${exists(c) ? '✔' : '✘'} \`${c}\``);
  const refs = t.rows.map((n) => `#${n}`);
  out(`* ${t.label}: ${present.join(', ') || 'no module of its own (generic passes only)'}${refs.length ? `; KNOWN-ISSUES ${refs.join(', ')}` : ''}`);
}
out();

out('## Closed or non-redistributable tools (public samples read as text)');
out();
out('| Record | Family | Version | Detected | Version read | Confidence | Unresolved | Passes applied |');
out('|---|---|---|---|---|---|---|---|');
for (const r of records) out(`| ${r.id} | ${r.family} | ${r.version || '-'} | ${r.detected ? r.detected.confidence : 'no'} | ${r.versionMatches == null ? 'n/a' : r.versionMatches ? 'yes' : 'no'} | ${r.confidence ? `${r.confidence.level} (${r.confidence.score})` : 'n/a'} | ${r.unresolved ?? 'n/a'} | ${(r.steps || []).filter((s) => s.status === 'applied').length} |`);
out();
out('These rows rest on one to two public scripts per version (KNOWN-ISSUES 23): they say the engine reads the sample, not that it covers the tool.');
out();

out('## The public collection, by folder');
out();
out(`Source: ${db.collection.source} at ${db.collection.commit.slice(0, 12)}, ${db.collection.files} files. "Identified" means the detector named the folder’s tool; the rest are classified (what the script is made of), never left blank.`);
out();
out('| Folder | Files | Parsed | Identified | Unidentified, by class |');
out('|---|---|---|---|---|');
for (const f of db.collection.folders) out(`| ${f.label} | ${f.files} | ${f.parsed} | ${f.identified} | ${Object.entries(f.classOfUnidentified || {}).map(([k, v]) => `${k} ${v}`).join(', ') || '-'} |`);
out();

out('## Backlog items and their state');
out();
for (const b of db.backlog) out(`* **${b.item}** (${b.state}): ${b.detail}`);
out();

const open = [...issues.matchAll(/^\| (\d+b?) \| ([^|]+)\|/gm)].filter((m) => !/~~/.test(m[2])).map((m) => `* #${m[1]}: ${m[2].trim().replace(/\s+/g, ' ').slice(0, 220)}`);
out('## Open issues (from docs/KNOWN-ISSUES.md)');
out();
lines.push(...open);
out();

const text = `${lines.join('\n')}\n`;
if (process.argv.includes('--write')) { fs.writeFileSync(path.join(root, 'docs/AUDIT.md'), text); console.log(`wrote docs/AUDIT.md (${text.length} bytes)`); } else process.stdout.write(text);
