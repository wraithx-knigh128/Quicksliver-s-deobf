#!/usr/bin/env node
// Builds src/recover/charmodel.js: a character trigram model of English words, trained on this repository's own documentation (docs/*.md).
// It is used to rank candidate plaintexts (src/recover/keysearch.js); it carries no word list and nothing from the test fixtures' sources.
//
//   node tools/models/build-charmodel.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const docs = path.join(repo, 'docs');
let text = '';
for (const f of fs.readdirSync(docs).sort()) if (f.endsWith('.md')) text += fs.readFileSync(path.join(docs, f), 'utf8') + '\n';
// words only: code spans, URLs and paths carry identifiers of this project, not English
text = text.replace(/`[^`\n]*`/g, ' ').replace(/https?:\/\/\S+/g, ' ').replace(/\S*[\/\\]\S*/g, ' ');
const words = (text.match(/[A-Za-z]{2,}/g) || []).map((w) => w.toLowerCase());
const N = 27;   // a-z and the word boundary (index 26)
const idx = (c) => (c === ' ' ? 26 : c.charCodeAt(0) - 97);
const counts = new Float64Array(N * N * N);
const ctx = new Float64Array(N * N);
for (const w of words) {
  const s = `  ${w} `;
  for (let i = 2; i < s.length; i++) {
    const a = idx(s[i - 2]); const b = idx(s[i - 1]); const c = idx(s[i]);
    counts[(a * N + b) * N + c]++;
    ctx[a * N + b]++;
  }
}
// add-k smoothing; cost = -log2 p, quantised to quarter bits, capped at 63.75
const k = 0.05;
const bytes = new Uint8Array(N * N * N);
for (let ab = 0; ab < N * N; ab++) {
  for (let c = 0; c < N; c++) {
    const p = (counts[ab * N + c] + k) / (ctx[ab] + k * N);
    bytes[ab * N + c] = Math.min(255, Math.round(-Math.log2(p) * 4));
  }
}
const b64 = Buffer.from(bytes).toString('base64');
const out = `// Generated by tools/models/build-charmodel.mjs from docs/*.md (${words.length} words). Do not edit.
// Character trigram costs over a-z plus the word boundary: TRIGRAM[(a*27+b)*27+c] = -log2 p(c | a b) in quarter bits.
const B64 = '${b64}';
const decode = (s) => { if (typeof atob === 'function') { const t = atob(s); const u = new Uint8Array(t.length); for (let i = 0; i < t.length; i++) u[i] = t.charCodeAt(i); return u; } return Uint8Array.from(Buffer.from(s, 'base64')); };
export const TRIGRAM = decode(B64);
`;
fs.writeFileSync(path.join(repo, 'src', 'recover', 'charmodel.js'), out);
console.log(`src/recover/charmodel.js: ${words.length} words, ${bytes.length} trigram costs`);

// ---- the common-word list (SCOWL levels 10 and 20, via the MIT-licensed npm package wordlist-english 1.2.1) -------------------------------
// The package is not a dependency of the site: point --scowl at its unpacked directory to regenerate src/recover/wordlist.js.
const scowlAt = process.argv.indexOf('--scowl');
if (scowlAt > 0) {
  const dir = process.argv[scowlAt + 1];
  const words = new Set();
  for (const n of [10, 20]) for (const w of JSON.parse(fs.readFileSync(path.join(dir, `english-words-${n}.json`), 'utf8'))) if (/^[a-z]{2,}$/.test(w)) words.add(w);
  const list = [...words].sort();
  const js = `// Generated by tools/models/build-charmodel.mjs --scowl <dir> from SCOWL size 10 and 20 (english-words-10/20.json of the npm package
// wordlist-english 1.2.1, MIT). Copyright 2000-2016 by Kevin Atkinson; see THIRD_PARTY_NOTICES.md for the notice. Do not edit.
export const COMMON_WORDS = new Set('${list.join(' ')}'.split(' '));
`;
  fs.writeFileSync(path.join(repo, 'src', 'recover', 'wordlist.js'), js);
  console.log(`src/recover/wordlist.js: ${list.length} words`);
}
