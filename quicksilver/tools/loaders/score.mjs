// Score Loader Intelligence on tests/corpus/remote-loaders: retrieval, payload, reconstruction and behaviour, each counted on its own.
// Behaviour: the reconstructed program and the retrieved payload are run on the reference Lua (QS_LUA_PYTHON) and their output compared.
//   node tools/loaders/score.mjs [--write]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { manifest, runCase, dir } from './harness.mjs';
import { decodePayload } from '../../src/loader/payload.js';

const write = process.argv.includes('--write');
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
let oracle = null;
if (process.env.QS_LUA_PYTHON) oracle = await import('../../tests/helpers/lua-oracle.mjs');

const rows = [];
for (const c of manifest().cases) {
  const { report } = await runCase(c, { sandbox: true });
  for (const [i, s] of report.stages.entries()) {
    const row = { case: c.id, category: c.category, stage: i + 1, depth: s.depth, route: s.route.route, transport: s.transport ? (s.transport.ok ? 'ok' : `failed ${s.transport.status}`) : '—', payload: s.payload ? `${s.payload.kind}${s.payload.layers.length ? ` (${s.payload.layers.map((l) => l.kind).join('→')})` : ''}` : '—', outcome: s.outcome, programs: [] };
    for (const p of s.programs || []) {
      const pr = { families: p.families, level: p.reconstruction ? p.reconstruction.level : null, behaviour: null };
      if (oracle && p.output != null && !p.nestedLoader) {
        // the payload text as retrieved (after transport layers) vs the reconstruction
        const spec = c.service[s.request.address] || c.service[`provider:roblox-asset:${s.request.address}`];
        let payloadText = null;
        if (spec && spec.file) {
          const d = decodePayload(new Uint8Array(fs.readFileSync(path.join(dir, 'bodies', spec.file))));
          payloadText = d.text ?? (d.scripts && d.scripts[0] ? Buffer.from(d.scripts[0].source, 'utf8').toString('latin1') : null);
        }
        if (payloadText) {
          const [a, b] = await Promise.all([oracle.runLua(payloadText), oracle.runLua(p.output)]);
          pr.behaviour = !a.ok ? 'payload does not run standalone' : !b.ok ? 'reconstruction errors' : a.stdout === b.stdout ? 'same' : 'different';
        }
      }
      row.programs.push(pr);
    }
    rows.push(row);
  }
}
if (oracle) oracle.stopOracle();
const n = (f) => rows.filter(f).length;
const summary = {
  cases: manifest().cases.length,
  stages: rows.length,
  retrievable: n((r) => r.route !== 'none' && r.route !== 'manual' && r.route !== 'owner'),
  transportOk: n((r) => r.transport === 'ok'),
  payloadIsCode: n((r) => r.programs.length > 0),
  reconstructed: n((r) => r.outcome === 'retrieved-reconstructed'),
  plain: n((r) => r.outcome === 'retrieved-plain'),
  unrecoverable: n((r) => r.outcome === 'retrieved-unrecoverable'),
  behaviourSame: rows.flatMap((r) => r.programs).filter((p) => p.behaviour === 'same').length,
  behaviourChecked: rows.flatMap((r) => r.programs).filter((p) => p.behaviour && p.behaviour !== 'payload does not run standalone').length,
};
const md = ['# Loader Intelligence scorecard', '', 'Generated by `node tools/loaders/score.mjs --write` on `tests/corpus/remote-loaders` (fixtures of this repository behind a mock service, through the real `api/fetch.js` / `api/retrieve.js` handlers). Each stage is counted on its own: an HTTP success is not a payload, a payload is not a reconstruction, a reconstruction is not verified behaviour.', '',
  '| Measure | Count |', '|---|---|',
  ...Object.entries({ 'loader cases': summary.cases, 'requests (stages)': summary.stages, 'with an authorised route': summary.retrievable, 'transport succeeded': summary.transportOk, 'payload is code': summary.payloadIsCode, 'reconstructed (obfuscated → high/medium)': summary.reconstructed, 'plain code (nothing to remove)': summary.plain, 'retrieved, not reconstructed': summary.unrecoverable, 'behaviour checked on the reference Lua': summary.behaviourChecked, '… and the same as the retrieved payload': summary.behaviourSame }).map(([k, v]) => `| ${k} | ${v} |`),
  '', '| Case | Category | Stage | Route | Transport | Payload | Outcome | Obfuscator → confidence | Behaviour |', '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.case} | ${r.category} | ${r.stage}${r.depth ? ` (depth ${r.depth})` : ''} | ${r.route} | ${r.transport} | ${r.payload} | ${r.outcome} | ${r.programs.map((p) => `${p.families.join('+') || '—'} → ${p.level || '—'}`).join('; ') || '—'} | ${r.programs.map((p) => p.behaviour || '—').join('; ') || '—'} |`), ''].join('\n');
if (write) {
  fs.writeFileSync(path.join(root, 'docs', 'LOADER-SCORECARD.md'), md);
  fs.writeFileSync(path.join(root, 'data', 'research', 'loader-scorecard.json'), JSON.stringify({ summary, rows }, null, 1));
}
console.log(summary);
