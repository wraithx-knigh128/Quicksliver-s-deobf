// Prompt XV: regression tests for the deep reverse-engineering work, on committed fixtures and small controlled programs.

import test, { after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bytesToBinary } from '../src/core/bytes.js';
import { parse } from '../src/core/parser.js';
import { print } from '../src/core/printer.js';
import { recover } from '../src/recover/pipeline.js';
import { evaluatePass } from '../src/passes/evaluate.js';
import { removeGuardPrefix } from '../src/recover/prometheus.js';
import * as oracle from './helpers/lua-oracle.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const corpus = path.join(here, 'corpus');
const read = (p) => bytesToBinary(fs.readFileSync(p));
const run = (src) => recover(src, { sandbox: { enabled: true } });
const noOracle = !oracle.available && 'no Lua oracle (QS_LUA_PYTHON)';
after(() => oracle.stopOracle?.());

// ---- Panda Obfuscator (Prometheus-Modified v1.3): generated in run_isolated.py, compared with the original programs -----------------------------------

const panda = JSON.parse(fs.readFileSync(path.join(corpus, 'obfuscated/panda/manifest.json'), 'utf8'));

test('panda: the fixtures were generated by the tool in isolation, and what the tool could not do is recorded', () => {
  assert.match(panda.source, /Panda-Repositories\/Prometheus-Modified/);
  const ok = panda.entries.filter((e) => e.status === 'ok');
  assert.equal(ok.length, 32, 'Minify, Weak, Medium, Strong for eight programs');
  // the Luau presets stop inside the tool: `is` is used at parser.lua:208 and declared as a local at line 270
  const luau = panda.entries.filter((e) => /LuaU|Xenon|Roblox/.test(e.config));
  assert.ok(luau.length === 24 && luau.every((e) => e.status === 'tool-error' && /global 'is'/.test(e.error)));
});

for (const config of ['Weak', 'Medium', 'Strong']) {
  for (const s of ['s01_minify_basic', 's04_control_flow', 's06_combined']) {
    test(`panda ${config} ${s}: lifted (disguised dispatcher tests, anti-tamper with a random message) and runs as the original`, { skip: noOracle }, async () => {
      const r = run(read(path.join(corpus, `obfuscated/panda/${s}__${config}.lua`)));
      assert.ok(r.steps.some((x) => x.id === 'prometheus.vmify' && x.status === 'applied'), 'the VM is rebuilt');
      const want = await oracle.runLua(read(path.join(corpus, 'originals', `${s}.lua`)), 'lua51');
      const got = await oracle.runLua(r.output, 'lua51');
      assert.ok(got.ok && got.stdout === want.stdout, got.error || 'stdout differs');
      assert.equal(r.confidence.level, 'high', JSON.stringify(r.report.unresolved));
    });
  }
}

test('anti-tamper: the guard Vmify took apart, ending in `if not flag then fail() end`, is removed when it holds the line-number probe and touches nothing else', () => {
  const guard = `
local function f() end
local flag = true
local function fail() error("kq3J") end
pcall(f)
local function probe() return "a" / (1 - "b" ^ 2) end
local line = tonumber(string.gmatch(tostring(({ pcall(probe) })[2]), ":(%d*):")())
flag = flag and line ~= nil
if not flag then fail() end
`;
  const ast = parse(`${guard}print("program")`);
  assert.ok(removeGuardPrefix(ast).changed > 0);
  assert.equal(print(ast).trim(), 'print("program")');
  // the same statements, when the program reads one of the guard's locals, are left alone
  const keep = parse(`${guard}print(line)`);
  assert.equal(removeGuardPrefix(keep).changed, 0);
  // without the probe or the message it is not a guard
  const plain = parse('local flag = true\nlocal x = 1\nflag = flag and x == 1\nif not flag then error("no") end\nprint(x)');
  assert.equal(removeGuardPrefix(plain).changed, 0);
});

test('evaluate: a cache key held in a local inside a function is folded into its lookup when nothing in between calls anything', () => {
  const src = `
local store = {}
local function dec(s, k) if store[k] then return k end local o = "" for i = 1, #s do o = o .. string.char(string.byte(s, i) - 1) end store[k] = o return k end
local cache = setmetatable({}, { __index = store })
local function f()
  local k = dec("ifmmp", 5)
  local unrelated = 3
  local v = cache[k]
  return v, unrelated
end
print(f())`;
  const ast = parse(src);
  evaluatePass(ast, { sandbox: { enabled: true } });
  assert.match(print(ast), /"hello"/);
  // a call between the key and its use: not moved
  const ast2 = parse(src.replace('local unrelated = 3', 'local unrelated = tostring(3)'));
  evaluatePass(ast2, { sandbox: { enabled: true } });
  assert.match(print(ast2), /local k = dec\("ifmmp", 5\)/);
});

// ---- IronBrikked: a program the compiler compiles correctly is recovered exactly ------------------------------------------------------------------

const subset = path.join(corpus, 'controlled/luaxen-subset');

test('ironbrikked: a controlled program inside the subset LuaXen compiles correctly runs as the original after recovery (the reader is exact there)', { skip: noOracle }, async () => {
  const r = run(read(path.join(subset, 'c4_subset__ironbrikked.lua')));
  assert.ok(r.steps.some((x) => x.id === 'ironbrikked.vm' && x.status === 'applied'));
  const want = await oracle.runLua(read(path.join(subset, 'c4_subset.lua')), 'lua51');
  const got = await oracle.runLua(r.output, 'lua51');
  assert.equal(got.stdout, want.stdout);
  // the numeric for loop reads its own counter R(A) (luac reads R(A+3)); the reader makes those reads the loop variable
  assert.match(r.output, /list\[i\]/);
});

test('ironbrikked: closures are given the upvalue links their own instructions use (the generator writes 0 there)', () => {
  const r = run(read(path.join(subset, 'c5_closure__ironbrikked.lua')));
  assert.match(r.output, /print\(\w+, 42\)/, 'the closure reads both upvalues: name and base + 2 folded');
});

test('ironbrikked: `local r = f()` is compiled with the result thrown away and its register reused, and recovery follows the compiled program', { skip: noOracle }, async () => {
  const r = run(read(path.join(subset, 'c5_closure__ironbrikked.lua')));
  const got = await oracle.runLua(r.output, 'lua51');
  assert.match(got.stdout, /^answer\t42\ntwice\tfunction/);
});

// ---- MoonVeil 2.1.0: the function layout is read off each build's own reader, and the data is read to its last byte -------------------------------

const mv21 = (n) => path.join(here, '..', 'local', 'moonveil', `v2.1.0_sample${n}.lua`);
for (const [n, marker, functions, instructions] of [[6, 192, 3, 40], [7, 93, 2, 28]]) {
  test(`moonveil 2.1.0 sample ${n}: the build's schema is derived from its reader and the program data is read exactly (${functions} functions, ${instructions} instructions)`, { skip: !fs.existsSync(mv21(n)) && 'local MoonVeil samples are not in the repository' }, () => {
    const r = recover(read(mv21(n)), { sandbox: { enabled: true } });
    const st = r.steps.find((x) => x.id === 'moonveil.program21');
    assert.ok(st, 'the step ran');
    assert.match(String(st.detail), new RegExp(`read to its last byte .*function marker ${marker}.*${functions} function\\(s\\), ${instructions} instruction\\(s\\)`));
    assert.notEqual(r.confidence.level, 'high', 'nothing is rebuilt from it');
  });
}

import { readProgram21, Schema21Error } from '../src/recover/moonveil-vm/schema21.js';

test('moonveil 2.1.0 program reader: a schema that does not fit the data is refused (bytes left over, or an opcode without a layout)', () => {
  const schema = { marker: 192, stubStrings: 2, steps: [{ kind: 'varint' }, { kind: 'instructions', layouts: new Map([[0, [[26, 'B']]]]) }, { kind: 'varint' }, { kind: 'constants', tags: new Map() }, { kind: 'varint' }, { kind: 'functions' }] };
  // 0 strings; marker; 1 instruction (op 0, one operand); 0 constants; 0 functions
  const ok = Uint8Array.from([0, 192, 1, 0, 5, 0, 0]);
  assert.equal(readProgram21(ok, schema).stats.instructions, 1);
  assert.throws(() => readProgram21(Uint8Array.from([0, 192, 1, 0, 5, 0, 0, 9]), schema), Schema21Error, 'a byte left over');
  assert.throws(() => readProgram21(Uint8Array.from([0, 192, 1, 7, 5, 0, 0]), schema), Schema21Error, 'opcode 7 has no layout');
});
