// A fourth pass of open-source obfuscators: AzureVM, the single-page obfuscator (simple-lua-obfuscator's index.html), Clyde, and the Stealth-X
// samples it was compared with.
//
// What is tested, and on what:
//   * AzureVM, the page obfuscator and Clyde (all MIT): their real output is committed (tests/corpus/obfuscated/{azurevm,simple_html,clyde}), made by
//     running each tool in an isolated runner. Detection, the "VM is not recovered" statement, and recovery where the technique is reversible are
//     checked against it.
//   * Stealth-X has no licence, so its samples are not stored; its signature is tested on short scripts written for this test in the same shape.

import test, { after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { recover } from '../src/recover/pipeline.js';
import { detect } from '../src/detect/detect.js';
import { fidelity } from '../src/core/fidelity.js';
import { parse } from '../src/core/parser.js';
import { print } from '../src/core/printer.js';
import * as oracle from './helpers/lua-oracle.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const corpus = path.join(here, 'corpus');
const read = (p) => fs.readFileSync(p).toString('latin1');
const skipOracle = oracle.available ? false : 'QS_LUA_PYTHON is not set (reference Lua unavailable)';
after(() => oracle.stopOracle());
const family = (d, id) => d.families.find((f) => f.id === id);
const manifest = (dir) => JSON.parse(fs.readFileSync(path.join(corpus, 'obfuscated', dir, 'manifest.json'), 'utf8'));
const fixture = (dir, e) => read(path.join(corpus, 'obfuscated', dir, e.file));
const ok = (m) => m.entries.filter((e) => e.status === 'ok');
const original = (name) => read(path.join(corpus, 'originals', name));

// ---- AzureVM ---------------------------------------------------------------------------------------------------------------------------------

const azure = manifest('azurevm');

test('AzureVM: the fixtures are real tool output under the MIT licence, at six presets', () => {
  assert.equal(azure.licence, 'MIT');
  assert.deepEqual([...new Set(ok(azure).map((e) => e.config))].sort(), ['AzureGod15', 'AzureGodUltra', 'Balanced', 'Fast', 'Luraph', 'Luraph14']);
  assert.ok(ok(azure).length >= 40);
});

for (const e of ok(azure).filter((x) => x.config !== 'Balanced' && x.sample === 's06_combined.lua')) {
  test(`azurevm/${e.config}: named from its header and the library prelude, and reported as a VM that is not recovered`, () => {
    const src = fixture('azurevm', e);
    const d = detect(src);
    const f = family(d, 'azurevm');
    assert.ok(f && f.confidence >= 0.95, `confidence ${f && f.confidence}`);
    assert.ok(f.evidence.some((x) => x.rule === 'payload' && x.unrecoverable), 'the payload is flagged');
    assert.equal(d.families.filter((x) => x.confidence >= 0.5).length, 1, 'no other family is claimed');
    const r = recover(src, {});
    assert.equal(r.ok, true);
    assert.ok(r.confidence.score <= 0.4, `confidence ${r.confidence.score}: a VM is still present`);
    assert.ok(r.confidence.hints.includes('trace'));
  });
}

test('AzureVM: the header alone names the tool; the Balanced preset (Prometheus-style) is recognised through its watermark as well', () => {
  const header = '-- Generated by AzureVM (template mode 2)\nprint("hi")\n';
  assert.ok(family(detect(header), 'azurevm').evidence.some((x) => x.rule === 'banner'));
  const e = ok(azure).find((x) => x.config === 'Balanced' && x.sample === 's06_combined.lua');
  const d = detect(fixture('azurevm', e));
  assert.ok(family(d, 'azurevm') && family(d, 'azurevm').evidence.some((x) => x.rule === 'watermark'));
  assert.ok(family(d, 'prometheus'), 'the Prometheus-style transforms are still recognised');
});

test('AzureVM: the payload tag is the same three letters Luraph uses, and that is not taken as Luraph', () => {
  const e = ok(azure).find((x) => x.config === 'Fast' && x.sample === 's06_combined.lua');
  const d = detect(fixture('azurevm', e));
  assert.ok(!family(d, 'luraph') || family(d, 'luraph').confidence < 0.5);
});

// ---- the single-page obfuscator -------------------------------------------------------------------------------------------------------------

const html = manifest('simple_html');

test('simple_html: real output of the page’s own JavaScript, MIT; the ones where the tool broke the program are labelled', () => {
  assert.equal(html.licence, 'MIT');
  assert.equal(ok(html).length, 8);
  assert.ok(ok(html).some((e) => e.behavior === 'equivalent'));
});

for (const e of ok(html)) {
  test(`simple_html/${e.sample}: the _D decoder is recognised and the program is rebuilt without running anything`, () => {
    const src = fixture('simple_html', e);
    const d = detect(src);
    assert.ok(family(d, 'simple_html') && family(d, 'simple_html').confidence >= 0.9);
    const r = recover(src, { sandbox: { enabled: false } });
    assert.equal(r.ok, true);
    assert.doesNotMatch(r.output, /_D\(\{/, 'no encoded string call is left');
    const f = fidelity(original(e.sample), r.output).score;
    assert.ok(f >= 0.9, `fidelity ${f}`);
  });
}

test('simple_html: a recovered fixture that the tool itself kept intact behaves like its original on a real Lua', { skip: skipOracle }, async () => {
  const e = ok(html).find((x) => x.behavior === 'equivalent');
  const src = fixture('simple_html', e);
  const r = recover(src, { sandbox: { enabled: false } });
  const a = await oracle.runLua(original(e.sample), e.runtime);
  const b = await oracle.runLua(r.output, e.runtime);
  assert.equal(a.ok, true);
  assert.equal(b.stdout, a.stdout);
});

// ---- Clyde -----------------------------------------------------------------------------------------------------------------------------------

const clyde = manifest('clyde');

test('Clyde: real output of the TypeScript build, MIT, in four modes; the one that could not be run is labelled', () => {
  assert.equal(clyde.licence, 'MIT');
  assert.deepEqual([...new Set(ok(clyde).map((e) => e.config))].sort(), ['rename', 'strings-flow', 'vm', 'vm-max']);
});

for (const e of ok(clyde).filter((x) => x.config === 'vm' || x.config === 'vm-max')) {
  test(`clyde/${e.config}/${e.sample}: the header and the escaped string.char name Clyde, and the VM is reported as not recovered`, () => {
    const src = fixture('clyde', e);
    const d = detect(src);
    const f = family(d, 'clyde');
    assert.ok(f && f.confidence >= 0.9, `confidence ${f && f.confidence}`);
    assert.equal(d.families.filter((x) => x.confidence >= 0.5).length, 1);
    const r = recover(src, {});
    assert.equal(r.ok, true);
    assert.ok(r.confidence.score <= 0.4, `confidence ${r.confidence.score}`);
  });
}

for (const e of ok(clyde).filter((x) => x.config === 'strings-flow' && x.sample === 's06_combined.lua')) {
  test('clyde/strings-flow: encoded strings are read back with the sandbox and the program is close to its original', () => {
    const r = recover(fixture('clyde', e), { sandbox: { enabled: true } });
    assert.equal(r.ok, true);
    const f = fidelity(original(e.sample), r.output).score;
    assert.ok(f >= 0.8, `fidelity ${f}`);
  });
}

// ---- Stealth-X (signature only, tested on scripts written for this test) -------------------------------------------------------------------------

const handlers = (n) => Array.from({ length: n }, (_, i) => `[0x${(0x572ff20f + i * 977).toString(16).toUpperCase()}]=function(a,b,c,d,e)local f=b.x end`).join(',');

test('Stealth-X: the header names it; the VM shape names it without the header and flags it as not recovered', () => {
  const header = '--[[\n  banner\nThis file secured by StealthxProtect Gen3.2 (https://obf.getstealthx.site/)\n\n]]\n\nreturn(function(...)return 1 end)(...)\n';
  const f = family(detect(header), 'stealthx');
  assert.ok(f && f.confidence >= 0.95 && f.version === 'Gen3.2');

  const vm = `return setmetatable({${handlers(25)},"STX@465:1667:8:5:s0:s5:"},{}):pSN()(...)`;
  const g = family(detect(vm), 'stealthx');
  assert.ok(g && g.confidence >= 0.8, JSON.stringify(g && g.confidence));
  assert.ok(g.evidence.every((x) => !x.unrecoverable) === false, 'the VM is flagged');
  const r = recover(vm, {});
  assert.ok(r.confidence.score <= 0.4, `confidence ${r.confidence.score}`);
});

test('Stealth-X: a few handlers on their own are not enough', () => {
  const small = `return setmetatable({${handlers(3)}},{}):go()(...)`;
  const f = family(detect(small), 'stealthx');
  assert.ok(!f || f.confidence < 0.5);
});

test('none of the new signatures fires on an original program or on output of the tools already supported', () => {
  const NEW = ['azurevm', 'simple_html', 'clyde', 'stealthx', 'kirus', 'moonveil'];
  const roots = ['originals', 'obfuscated/prometheus', 'obfuscated/hercules', 'obfuscated/ironbrew2', 'obfuscated/zenfus', 'obfuscated/loaders'];
  let checked = 0;
  for (const root of roots) {
    for (const name of fs.readdirSync(path.join(corpus, root))) {
      if (!/\.lua$/.test(name)) continue;
      const d = detect(read(path.join(corpus, root, name)));
      for (const f of d.families) if (NEW.includes(f.id)) assert.ok(f.confidence < 0.5, `${root}/${name} claims ${f.id} at ${f.confidence}`);
      checked++;
    }
  }
  assert.ok(checked > 150, `${checked} files checked`);
});

// ---- printer ----------------------------------------------------------------------------------------------------------------------------------

test('printer: a long array holding negative numbers prints the same way after it has been read back (a folded -1 is a Number, then a unary minus)', () => {
  const items = Array.from({ length: 60 }, (_, i) => (i % 7 === 3 ? `-${i + 1}` : String(i + 100))).join(', ');
  const ast = parse(`local t = { ${items} }\n`);
  // what a folding pass leaves behind: the unary minus replaced by a negative Number
  const fix = (n) => { if (!n || typeof n !== 'object') return n; if (Array.isArray(n)) return n.map(fix); if (n.type === 'Unary' && n.op === '-' && n.arg.type === 'Number') return { type: 'Number', value: -n.arg.value, raw: null }; for (const k of Object.keys(n)) if (typeof n[k] === 'object') n[k] = fix(n[k]); return n; };
  fix(ast);
  const first = print(ast);
  assert.match(first, /\{\n\s+100, 101, 102,/, 'packed, several per line');
  assert.equal(print(parse(first)), first, 'printing is stable');
});
